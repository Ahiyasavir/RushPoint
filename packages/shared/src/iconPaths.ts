// ── Stored reaction keys → drawn icons ────────────────────────────────────────
// Feed and live reactions are STORED under emoji keys (feedReactions.ts FEED_EMOJIS, reactions.ts
// REACTION_EMOJI). The keys stay exactly as they are, so no stored reaction changes meaning; only
// what the screen draws for them does.
export const REACTION_ICON: Record<string, IconName> = {
  '\u{1F44D}': 'thumbsUp', // thumbs up
  '\u{1F602}': 'faceLaugh', // tears of joy
  '\u{1F525}': 'flame', // fire
  '\u{1F62E}': 'faceWow', // open mouth
  '\u{1F44F}': 'clap', // clapping
  '❤️': 'heart', // red heart
  '❤': 'heart',
  '\u{1F680}': 'rocket', // rocket
};
/** The drawn icon for a stored reaction key; an unknown key draws a heart rather than nothing. */
export function reactionIcon(key: string): IconName {
  return REACTION_ICON[key] ?? 'heart';
}
